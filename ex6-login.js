// ส่วนที่ 1: ฟังก์ชัน login ตามลำดับการตรวจสอบสิทธิ์
// สร้างฟังก์ชันตรวจสอบสิทธิ์การเข้าใช้งานระบบ
function login(inputUser, inputPass, role, isActive, age){
    // ลำดับที่ 1: ตรวจสอบ username and password
    if(inputUser !== "admin" || inputPass !== "ce385pass"){
        return "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง"; // ถ้า User หรือ Password ไม่ถูกต้องจะปฏิเสธการเข้าใช้งานทันที
    }

    // ลำดับที่ 2: ตรวจสอบบัญชีถูกระงับ
    if(isActive === false){
        return "บัญชีนี้ถูกระงับการใช้งาน" // ถ้าบัญชีถูกระงับการใช้งาน จะไม่สามารถเข้าได้
    }

    // ลำดับที่ 3: ตรวจสอบอายุ
    if(age < 18){
        return "อายุไม่ถึงเกณฑ์"; // ถ้าอายุน้อยกว่า 18 ปี จะไม่สามารถเข้าได้
    }

    // ลำดับที่ 4: ผ่านทุกข้อ และเป็น "อาจารย์" 
    if(role === "อาจารย์"){
        return "เข้าสู่ระบบสำเร็จ (สิทธิ์ผู้ดูแล)";
    }

    // ลำดับที่ 5: ผ่านทุกข้อ แต่เป็น "นักศึกษา"
    if(role === "นักศึกษา"){
        return "เข้าสู่ระบบสำเร็จ (สิทธิ์ทั่วไป)";
    }
    
    return "บทบาทผู้ใช้ไม่ถูกต้อง"; // กรณีที่ส่งมาไม่ใช่อาจารญ์และนักศึกษา
}

